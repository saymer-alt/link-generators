// Lab config generator for the #284 no-direct-egress synthetic test.
// Uses the EXACT vendored Builder runtime (web4core.runtime.js) from the repo
// clone, so scenario configs are byte-identical to real Builder output except
// clearly marked lab-only additions:
//   - external-controller (same emission as Builder webUI: true);
//   - VLESS ingress listener (stand-in for the public VLESS server; mihomo
//     1.19.31 inbound VLESS requires TLS, so a lab self-signed cert is used).
// Routing core (proxies, proxy-groups, rules) stays exactly as generated.
//
// Topology (all inside WSL, network namespaces):
//   root ns : destination HTTP server 10.210.0.1:8099  ("public control endpoint")
//             subscription HTTP server 10.210.0.1:8098 (provider-fetch target)
//             DNS logging stub 0.0.0.0:5300/udp        (DNS observation only)
//   vps ns  : 10.210.0.3 — the "VPS public IP" simulation; runs mihomo A
//             (Builder YAML + lab VLESS ingress listener on :8443)
//   egress ns: 10.211.0.2 — the "allowed external egress node"; runs mihomo B
//
// Leak criterion: destination log shows a request whose source IP is 10.210.0.3
// from the USER data plane => FAIL (direct egress with the VPS IP). A logged
// source 10.210.0.3 on the SUBSCRIPTION server is the documented service-plane
// bootstrap and is NOT a user-plane leak.
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';

// Tool-relative paths: the vendored runtime comes from THIS repository, the
// generated configs land in run/configs (gitignored; never committed).
import { fileURLToPath } from 'node:url';
const TOOL_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(TOOL_DIR, '..', '..');
const OUT = path.join(TOOL_DIR, 'run', 'configs');

const runtime = fs.readFileSync(path.join(REPO, 'web4core.runtime.js'), 'utf8');
const ctx = vm.createContext({
  URL, URLSearchParams, TextEncoder, TextDecoder, atob, btoa,
  crypto: { randomUUID: () => '00000000-0000-4000-8000-000000000001' },
});
vm.runInContext('Math.random = () => 0.5', ctx);
vm.runInContext(runtime, ctx);
const engine = ctx.web4core;

// Synthetic UUIDs (documented lab values, RFC 4122 variant bits set).
const INGRESS_UUID = '00000000-0000-4000-8000-000000000001';
const EGRESS_UUID = 'a1b2c3d4-0000-4000-8000-0000000000e2';
const DEAD_UUID = 'd4d4d4d4-0000-4000-8000-000000000d34';
const SNI = 'lab.local';

// Lab self-signed cert (generated by lab.sh before this script runs).
const cert = fs.readFileSync(path.join(TOOL_DIR, 'certs', 'server-cert.pem'), 'utf8').trim();
const key = fs.readFileSync(path.join(TOOL_DIR, 'certs', 'server-key.pem'), 'utf8').trim();
const pemYaml = (text) => text.split('\n').map((l) => '      ' + l).join('\n');
const TLS_BLOCK = `    certificate: |
${pemYaml(cert)}
    private-key: |
${pemYaml(key)}`;

const build = (input, options) => {
  const res = engine.buildFromRequest({ core: 'mihomo', input, options });
  if (res.kind !== 'yaml') throw new Error('unexpected build result kind: ' + res.kind);
  return res.data;
};

// Live upstream share link — standard VLESS+TLS form the Builder parses
// (allowInsecure=1 -> skip-cert-verify: true; sni -> servername).
const EGRESS_LINK =
  `vless://${EGRESS_UUID}@10.211.0.2:8442?security=tls&allowInsecure=1&sni=${SNI}#egress-live`;

// Lab-only additions appended to the Builder YAML for mihomo A.
const LAB_APPEND_A = `
# === LAB-ONLY (not Builder output) ===
external-controller: 0.0.0.0:9090
listeners:
  - name: vless-in
    type: vless
    port: 8443
    listen: 0.0.0.0
${TLS_BLOCK}
    users:
      - uuid: ${INGRESS_UUID}
`;

fs.mkdirSync(OUT, { recursive: true });
const write = (name, text) => {
  fs.writeFileSync(path.join(OUT, name), text);
  console.log('wrote', name, text.split('\n').length, 'lines');
};

// --- Scenario A: live upstream egress + one dead upstream (TEST-NET-1) ---
write('configA.yaml', build([EGRESS_LINK, `vless://${DEAD_UUID}@192.0.2.9:443#dead-upstream`].join('\n'),
  { addTun: false, addSocks: true, webUI: false }) + LAB_APPEND_A);

// --- Scenario B: full outage, both upstreams dead (TEST-NET-1) ---
write('configA-outage.yaml', build([
  `vless://${DEAD_UUID}@192.0.2.9:443#dead-upstream-1`,
  `vless://${DEAD_UUID}@192.0.2.8:443#dead-upstream-2`,
].join('\n'), { addTun: false, addSocks: true, webUI: false }) + LAB_APPEND_A);

// --- Scenario D: Sub Mode ON (provider fetch = service plane, must keep working) ---
write('configA-sub.yaml', build('http://10.210.0.1:8098/sub',
  { mihomoSubscriptionMode: true, addTun: false, addSocks: true, webUI: false }) + LAB_APPEND_A);

// --- Scenario D2: Sub Mode ON with a dead node in the subscription —
// provider fetch (service plane) must succeed while user plane fails closed ---
write('configA-sub-dead.yaml', build('http://10.210.0.1:8098/sub-dead',
  { mihomoSubscriptionMode: true, addTun: false, addSocks: true, webUI: false }) + LAB_APPEND_A);

// --- Lab infra: egress node B (the "allowed external egress") ---
// B is NOT generator output; as the exit node its MATCH,DIRECT is the transport
// bootstrap/exit semantics the owner contract explicitly allows (it dials the
// controlled destination — the "internet" — from the egress namespace only).
write('configB.yaml', `# LAB-ONLY egress node stand-in (not generator output)
mixed-port: 7891
allow-lan: false
mode: rule
log-level: warning
ipv6: false
listeners:
  - name: vless-in
    type: vless
    port: 8442
    listen: 0.0.0.0
${TLS_BLOCK}
    users:
      - uuid: ${EGRESS_UUID}
rules:
  - MATCH,DIRECT
`);

// --- Lab infra: client C (Joe Doe's phone stand-in; phone-side TUN is out of
// scope — from the VPS perspective the VLESS byte stream is identical) ---
write('configC.yaml', `# LAB-ONLY client stand-in (not generator output)
mixed-port: 7897
allow-lan: false
mode: rule
log-level: warning
ipv6: false
proxies:
  - name: ingress-a
    type: vless
    server: 10.210.0.3
    port: 8443
    uuid: ${INGRESS_UUID}
    tls: true
    servername: ${SNI}
    skip-cert-verify: true
    udp: true
proxy-groups:
  - name: PHONE
    type: select
    proxies: [ingress-a]
rules:
  - MATCH,PHONE
`);

// --- Lab DNS observation variant of A (outage, hostname request) ---
// Adds a lab dns section pointing at the logging stub to OBSERVE whether the
// VPS-originated resolver is used for user-plane hostnames. This variant is
// lab-instrumented and clearly marked; observations only, no PASS/FAIL claim.
write('configA-dns-observe.yaml', build([
  `vless://${DEAD_UUID}@192.0.2.9:443#dead-upstream-1`,
  `vless://${DEAD_UUID}@192.0.2.8:443#dead-upstream-2`,
].join('\n'), { addTun: false, addSocks: true, webUI: false }) + `
# === LAB-ONLY (not Builder output) ===
external-controller: 0.0.0.0:9090
dns:
  enable: true
  listen: 0.0.0.0:1053
  nameserver:
    - 10.210.0.1:5300
listeners:
  - name: vless-in
    type: vless
    port: 8443
    listen: 0.0.0.0
${TLS_BLOCK}
    users:
      - uuid: ${INGRESS_UUID}
`);

// Static self-checks mirrored from tests/no-direct-egress.cjs on the exact
// scenario configs (defense against a lab config that violates the policy).
for (const f of ['configA.yaml', 'configA-outage.yaml', 'configA-sub.yaml', 'configA-sub-dead.yaml']) {
  const text = fs.readFileSync(path.join(OUT, f), 'utf8');
  if (/^\s*-\s*["']?DIRECT["']?\s*$/m.test(text)) throw new Error(f + ': DIRECT member found in groups');
  if (/\bMATCH,DIRECT\b/.test(text)) throw new Error(f + ': MATCH,DIRECT rule found');
}
console.log('static self-checks OK');
